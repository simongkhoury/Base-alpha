# Packs the monster artwork in assets/monsters into js/artdata.js (WebP, base64) for the single-file build.
# icons/<name>.png: transparent head portraits. frames/<type>-NN.png: 8 walk frames then 8 grab frames.
import base64, io, json, pathlib, re
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'assets' / 'monsters'
ICON_KEYS = {'zombie': 'z', 'horde': 'h', 'tank': 'tk', 'speedy': 'sp', 'invisible': 'iv', 'sleepy_giant': 'sl', 'dancer': 'dn'}
def webp(im, q):
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
out = {'icon': {}, 'body': {}}
for name, k in ICON_KEYS.items():
    f = src / 'icons' / f'{name}.png'
    if f.exists(): out['icon'][k] = webp(Image.open(f).convert('RGBA').resize((128, 128), Image.LANCZOS), 88)
# body frames, grouped by type prefix (dancer -> dn); all frames of a type share one crop box so they don't jitter
groups = {}
for f in sorted((src / 'frames').glob('*.png')):
    m = re.match(r'(.+)-(\d+)\.png$', f.name)
    if m and m.group(1) in ICON_KEYS: groups.setdefault(ICON_KEYS[m.group(1)], []).append(f)
for k, files in groups.items():
    ims = [Image.open(f).convert('RGBA') for f in files]
    box = None
    for im in ims:
        b = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
        box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    w, h = box[2] - box[0], box[3] - box[1]; side = max(w, h)
    cx, by = (box[0] + box[2]) // 2, box[3]
    sq = (cx - side // 2, by - side, cx - side // 2 + side, by)            # square, feet on the bottom edge
    frames = [webp(im.crop(sq).resize((200, 200), Image.LANCZOS), 70) for im in ims]
    out['body'][k] = {'walk': frames[:8], 'grab': frames[8:16] or frames[:8]}
js = '// Generated by tools/make_art.py from assets/monsters. Monster head icons and body frames.\nexport const ART = ' + json.dumps(out) + ';\n'
(root / 'js' / 'artdata.js').write_text(js)
print(len(out['icon']), 'icons,', {k: len(v['walk']) + len(v['grab']) for k, v in out['body'].items()}, 'frames,', len(js) // 1024, 'KB')
