# Packs the monster artwork in assets/monsters (one folder per monster: icon-256.png, walk/00-07.png, grab/00-07.png)
#  - head icons -> js/artdata.js (WebP, base64, embedded in the page)
#  - body frames -> art/<key>-walk.webp and art/<key>-grab.webp (8-frame strips, loaded only when the AR scope is on)
import base64, io, json, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'assets' / 'monsters'; outdir = root / 'art'; outdir.mkdir(exist_ok=True)
KEYS = {'zombie': 'z', 'horde': 'h', 'tank': 'tk', 'speedy': 'sp', 'invisible': 'iv', 'sleepy_giant': 'sl', 'dancer': 'dn'}
FRAME = 192
man = json.loads((src / 'manifest.json').read_text()) if (src / 'manifest.json').exists() else {'enemies': {}}
def b64webp(im, q):
    b = io.BytesIO(); im.save(b, 'WEBP', quality=q, method=6); return 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
out = {'icon': {}, 'body': {}}
total = 0
for name, k in KEYS.items():
    d = src / name
    if (d / 'icon-256.png').exists(): out['icon'][k] = b64webp(Image.open(d / 'icon-256.png').convert('RGBA').resize((128, 128), Image.LANCZOS), 88)
    walk, grab = sorted((d / 'walk').glob('*.png')), sorted((d / 'grab').glob('*.png'))
    if not walk: continue
    ims = {'walk': [Image.open(f).convert('RGBA') for f in walk], 'grab': [Image.open(f).convert('RGBA') for f in (grab or walk)]}
    box = None   # one crop box for every frame of this monster, so walk and grab line up and nothing jitters
    for im in ims['walk'] + ims['grab']:
        b = im.getchannel('A').point(lambda a: 255 if a > 8 else 0).getbbox()
        if b: box = b if box is None else (min(box[0], b[0]), min(box[1], b[1]), max(box[2], b[2]), max(box[3], b[3]))
    side = max(box[2] - box[0], box[3] - box[1]); cx = (box[0] + box[2]) // 2
    sq = (cx - side // 2, box[3] - side, cx - side // 2 + side, box[3])    # square, feet on the bottom edge
    anim = man.get('enemies', {}).get(name, {}).get('animations', {})
    info = {}
    for a, frames in ims.items():
        strip = Image.new('RGBA', (FRAME * len(frames), FRAME))
        for i, im in enumerate(frames): strip.alpha_composite(im.crop(sq).resize((FRAME, FRAME), Image.LANCZOS), (i * FRAME, 0))
        f = outdir / f'{k}-{a}.webp'; strip.save(f, 'WEBP', quality=72, method=6); total += f.stat().st_size
        info[a] = {'src': f'art/{k}-{a}.webp', 'n': len(frames), 'ms': anim.get(a, {}).get('duration_per_frame_ms', 125 if a == 'walk' else 150)}
    out['body'][k] = info
js = '// Generated by tools/make_art.py from assets/monsters. Head icons (embedded) and body-frame strips (art/*.webp).\nexport const ART = ' + json.dumps(out) + ';\n'
(root / 'js' / 'artdata.js').write_text(js)
print(len(out['icon']), 'icons embedded,', len(js) // 1024, 'KB;', len(out['body']) * 2, 'strips,', total // 1024, 'KB in art/')
